_current = "en"

def set_lang(code: str) -> str:
    """Select language; unknown codes fall back to English. Returns active code."""
    global _current
    code = (code or "en").lower()
    _current = code if code in _STR else "en"
    return _current

def cur() -> str:
    return _current

def t(key: str, **kw) -> str:
    s = _STR.get(_current, {}).get(key, _STR["en"].get(key, key))
    try:
        return s.format(**kw)
    except Exception:
        return s
